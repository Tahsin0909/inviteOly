export const getAdminEventDetailsById = (id: string): IAdminEventDetails => {
  const matchedEvent = staticAdminEvents.find((e) => e.id === id);
  if (!matchedEvent) {
    return {
      ...staticAdminEventDetails,
      id,
    };
  }

  return {
    ...staticAdminEventDetails,
    id: matchedEvent.id,
    tier: matchedEvent.tier,
    hostName: matchedEvent.hostName,
    eventName: matchedEvent.title,
    eventDate: matchedEvent.date,
    endDate: matchedEvent.date,
    startTime: matchedEvent.time.split(" - ")[0] || "5:00 PM",
    endTime: matchedEvent.time.split(" - ")[1] || "11:00 PM",
    venue: matchedEvent.venue.split(",")[0]?.trim() || "Golden Bay Event Center",
    city: matchedEvent.venue.split(",")[1]?.trim() || "San Francisco",
    estimateGuestCount: matchedEvent.totalGuests,
    venueGuestCapacity: 400,
    assignedGuestsCount: matchedEvent.totalGuests,
    totalCapacity: 400,
    checkedInCount: Math.round(matchedEvent.totalGuests * 0.47),
    ticketGuests: staticAdminGuestTickets,
  };
};
